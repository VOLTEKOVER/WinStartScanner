const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('electronAPI', {
  runScan: () => ipcRenderer.invoke('run-scan'),
  checkUpdate: () => ipcRenderer.invoke('check-update'),
  downloadUpdate: (info) => ipcRenderer.invoke('download-update', info),
  applyUpdate: () => ipcRenderer.invoke('apply-update'),
  onScanProgress: (cb) => { ipcRenderer.on('scan-progress', (_e, v) => cb(v)); },
  onScanStatus: (cb) => { ipcRenderer.on('scan-status', (_e, v) => cb(v)); },
  onScanOrphanCount: (cb) => { ipcRenderer.on('scan-orphan-count', (_e, v) => cb(v)); },
  onUpdateProgress: (cb) => { ipcRenderer.on('update-progress', (_e, v) => cb(v)); },
  onAiText: (cb) => { ipcRenderer.on('ai-text', (_e, text) => cb(text)); },
  createShortcuts: (items) => ipcRenderer.invoke('create-shortcuts', items),
  getExeIcons: (entries) => ipcRenderer.invoke('get-exe-icons', entries),
  loadSettings: () => ipcRenderer.invoke('load-settings'),
  saveSettings: (s) => ipcRenderer.invoke('save-settings', s),
  setAutoStart: (enable) => ipcRenderer.invoke('set-auto-start', enable),
  showNotification: (opts) => ipcRenderer.invoke('show-notification', opts),
  openFolder: (which) => ipcRenderer.invoke('open-folder', which),
  windowShow: () => ipcRenderer.send('window-show'),
  windowReload: () => ipcRenderer.send('window-reload'),
  windowMinimize: () => ipcRenderer.send('window-minimize'),
  windowMaximize: () => ipcRenderer.send('window-maximize'),
  windowClose: () => ipcRenderer.send('window-close'),
  getWindowState: () => ipcRenderer.invoke('get-window-state'),
  onMaximizeChange: (cb) => { ipcRenderer.on('window-maximized', (_e, v) => cb(v)); },
  onStartScan: (cb) => { ipcRenderer.on('start-scan', () => cb()); },
  readStartMenu: () => ipcRenderer.invoke('read-startmenu'),
  applyOrganization: (actions) => ipcRenderer.invoke('apply-organization', actions),
  checkBrokenLinks: () => ipcRenderer.invoke('check-broken-links'),
  deleteLnk: (lnkPath) => ipcRenderer.invoke('delete-lnk', lnkPath),
  createBackup: () => ipcRenderer.invoke('create-backup'),
  restoreBackup: (id) => ipcRenderer.invoke('restore-backup', id),
  deleteBackup: (id) => ipcRenderer.invoke('delete-backup', id),
  listBackups: () => ipcRenderer.invoke('list-backups'),
  loadHistory: () => ipcRenderer.invoke('load-history'),
  saveScanHistory: (entry) => ipcRenderer.invoke('save-scan-history', entry),
  loadScanHistory: () => ipcRenderer.invoke('load-scan-history'),
  aiSmartSelect: (orphans) => ipcRenderer.invoke('ai-smart-select', orphans),
  aiSmartSelectAuto: (orphans) => ipcRenderer.invoke('ai-smart-select-auto', orphans),
  aiOrganizeAuto: (items) => ipcRenderer.invoke('ai-organize-auto', items),
  aiOrganize: (items) => ipcRenderer.invoke('ai-organize', items),
  aiLoadResponse: (respPath) => ipcRenderer.invoke('ai-load-response', respPath),
  checkOpenCode: () => ipcRenderer.invoke('check-opencode'),
  clearTemp: () => ipcRenderer.invoke('clear-temp'),
  getAppInfo: () => ipcRenderer.invoke('get-app-info'),
});
